# ==========================================
# Part 6.4：SFT 评估指标 — Exact Match 和 Token F1
# ==========================================
# 本模块实现两种最基础的文本生成评估指标，用于衡量 SFT 模型
# 生成的回答与标准答案之间的匹配程度。
#
# 为什么需要评估指标？
#   训练 loss 只能告诉你"模型对训练数据的拟合程度"，
#   但无法回答"模型生成的回答是否正确/合理"。
#   需要独立的评估指标来衡量模型的实际输出质量。
#
# 两种指标的定位：
#   Exact Match（精确匹配）：最严格的标准——归一化后的文本必须完全一致。
#     适用于事实型问答（如"法国的首都是？"），不接受任何细微差异。
#   Token F1（词级别 F1）：更宽松的标准——计算预测词和标准答案词的
#     重叠程度。适用于生成型任务（如摘要、长回答），允许合理表述差异。
#
# 本模块目前未被 orchestrator.py 调用（Demo 中只目测输出），
# 但为未来扩展自动评估提供了基础。

from __future__ import annotations
import re
from typing import List, Tuple


# ==========================================
# _normalize()：文本归一化 — 评估前的"公平尺度"
# ==========================================
# 文本评估中最常见的坑：模型输出 "Red, yellow, and blue."
# 而标准答案是 "red  yellow  blue"。这两个答案在语义上等价，
# 但直接字符串比较会判为不同——这对模型不公平。
#
# 归一化操作消去了所有无关的"写法差异"，只保留"内容信号"：
#   1. 转小写：消除大小写差异（"Hello" vs "hello"）
#   2. 去标点：将非字母数字字符替换为空格（消除 ".", "," , "!" 等差异）
#   3. 合并空白：多个连续空格压缩为一个，去掉首尾空白
#
# 类比：归一化相当于考试前的"统一答题纸"——
#   不管学生用钢笔还是铅笔、字迹潦草还是工整，
#   只比较答案的内容本身。
def _normalize(s: str) -> str:
    # ─── 步骤 1：全部转小写 ───
    # 语法：str.lower() 返回全小写副本，不修改原字符串。
    # "Hello World" → "hello world"
    s = s.lower()

    # ─── 步骤 2：去掉标点符号 ───
    # 语法：re.sub(pattern, replacement, string) 用正则表达式做全局替换。
    # 正则 [^a-z0-9\s] 的含义逐字符拆解：
    #   [...]   → 字符类，匹配方括号内的任意一个字符
    #   ^       → 取反（在字符类开头的 ^ 表示"非"）
    #   a-z     → 所有小写字母
    #   0-9     → 所有数字
    #   \s      → 所有空白字符（空格、tab、换行等）
    #   [^a-z0-9\s] → 匹配"既不是字母、也不是数字、也不是空白"的字符
    # 替换为 " "（空格），例如：
    #   "hello, world!" → "hello  world "
    s = re.sub(r"[^a-z0-9\s]", " ", s)

    # ─── 步骤 3：合并多余空白 ───
    # 正则 \s+ 匹配一个或多个连续空白字符。
    # 替换为一个空格 " "，压缩所有多余空白。
    # .strip() 去掉首尾空白。
    # 最终效果："hello   world  " → "hello world"
    s = re.sub(r"\s+", " ", s).strip()

    return s


# ==========================================
# exact_match()：精确匹配分数
# ==========================================
# 最严格的评估标准：归一化后两个文本必须逐字符完全一致。
#
# 返回值：1.0（完全匹配）或 0.0（不匹配）。
# 虽然中间值是可能的（如部分匹配场景），但 exact match 的定义就是二元的。
#
# 适用场景：短答案事实型问答、多选选择题、分类任务。
# 不适用场景：摘要生成、创意写作、长文本生成（要求一字不差太苛刻）。
def exact_match(pred: str, gold: str) -> float:
    # 语法：float(True) = 1.0, float(False) = 0.0。
    # 在 Python 中 bool 是 int 的子类：True == 1, False == 0。
    # 调用 float() 是为了函数签名承诺返回 float 类型。
    return float(_normalize(pred) == _normalize(gold))


# ==========================================
# token_f1()：词级别 F1 分数
# ==========================================
# 一种更宽松的评估标准，衡量预测文本中的词与标准答案中的词的
# 重叠程度。F1 是精确率（Precision）和召回率（Recall）的调和平均数。
#
# 数学定义：
#   Precision = 预测词中命中了多少个标准答案词 / 预测词总数
#              = "模型说的里面有多少是对的"
#   Recall    = 标准答案词中被预测命中了多少个 / 标准答案词总数
#              = "标准答案里的要点模型提到了几个"
#   F1 = 2 × P × R / (P + R)
#              = 精确率和召回率的调和平均，平衡二者
#
# 为什么用 F1 而不是准确率（Accuracy）？
#   F1 同时考虑"说对了多少"和"漏掉了多少"两个维度。
#   准确率只看正确比例，会被"预测词很多但都对"的情况欺骗。
#
# 为什么是"调和平均"而不是"算术平均"？
#   调和平均对极端值更敏感：(0 + 1)/2 = 0.5，但 2×0×1/(0+1) = 0。
#   如果精确率为 0（全是胡说八道），F1 直接为 0——这才是合理的。
#
# 注意：此处的"词"是归一化后空格分割的结果，不是语言学上的词。
# 对于英语来说这基本合理（词之间有空格），对中文需要先分词。
def token_f1(pred: str, gold: str) -> float:
    # ─── 归一化 + 分词 ───
    # 语法：str.split() 按任意空白字符分割，返回单词列表。
    # 默认（无参数）情况下还会自动去掉首尾空白并合并连续空白。
    p = _normalize(pred).split()   # 预测文本的词列表，如 ["red", "yellow", "blue"]
    g = _normalize(gold).split()   # 标准答案的词列表，如 ["red", "yellow", "blue", "green"]

    # ─── 边界情况处理 ───
    # 两者都为空（如预测和答案都是空字符串）：完美匹配！
    if not p and not g:
        return 1.0
    # 任一为空（一个有词、一个没词）：零匹配。
    # 语法：not p or not g 在先检查过两者都为空之后，
    # 能到这里说明至少一个非空，所以是"一空一不空"的情况。
    if not p or not g:
        return 0.0

    # ─── 计算重叠词数 ───
    # 遍历预测词列表，统计有多少词也出现在标准答案中。
    # 注意：这里对标准答案用 .copy() 做副本，逐个消耗匹配到的词。
    # 为什么需要消耗（gp.remove(t)）？
    #   因为如果一个词在标准答案中出现过但已被匹配，不应被重复计数。
    #   例如 pred=["red","red"], gold=["red"] → 第一个 red 匹配成功并消耗掉
    #   gold 中的 red，第二个 red 匹配失败 → common=1，正确。
    #   如果不消耗，两个 red 都会匹配成功 → common=2，错误（gold 只有一个 red）。
    common = 0
    gp = g.copy()            # 消耗副本——每次匹配成功后删除对应词
    for t in p:              # 遍历预测词
        if t in gp:           # 检查标准答案中是否还有这个词
            gp.remove(t)      # 匹配成功：从副本中移除此词（防止重复匹配）
            common += 1       # 重叠计数 +1

    # 无重叠词 → F1 = 0
    if common == 0:
        return 0.0

    # ─── 计算精确率和召回率 ───
    # Precision：预测词中"命中"的比例（"模型说的正确率"）
    prec = common / len(p)
    # Recall：标准答案词中"被找到"的比例（"答案覆盖度"）
    rec  = common / len(g)

    # ─── F1 = 2 × P × R / (P + R)，调和平均 ───
    # 当 P 和 R 都很高时 F1 才高；任一方很低则 F1 被拉低。
    # 例如：P=1.0, R=0.3 → F1 ≈ 0.46（虽然模型说的全对，但只覆盖了 30% 的答案要点）
    return 2 * prec * rec / (prec + rec)
