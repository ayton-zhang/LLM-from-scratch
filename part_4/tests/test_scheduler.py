# ==========================================
# 测试：WarmupCosineLR 学习率调度器的行为正确性
# ==========================================
# 学习率调度器（LR Scheduler）是训练的"方向盘"——
# 它决定了每一步优化器用多大的学习率去更新参数。
# 这个测试验证 WarmupCosineLR 的四个关键特性：
#   1. 学习率从不超过 base_lr（不会"超速"甩飞参数）
#   2. warmup 阶段学习率单调上升（从 0 逐步爬上 base_lr）
#   3. cosine 衰减阶段学习率逐步下降（训练后期步伐越来越小）
#   4. 调度器与优化器正确交互（能通过 param_groups 读写 lr）
#
# 为什么 warmup + cosine decay 是主流方案（GPT-3、LLaMA 都在用）？
#   - warmup：训练初始时参数是随机的，梯度很"吵"，
#     如果一上来就用全量学习率，容易把参数震飞甚至梯度爆炸。
#     warmup 像开车前先松手刹、轻踩油门起步。
#   - cosine decay：训练后期模型已经接近收敛，
#     需要越来越小的步子才能精确"降落到最优解"。
#     余弦曲线比线性下降更光滑，能减少后期震荡（论文验证过）。

from lr_scheduler import WarmupCosineLR

# ==========================================
# DummyOpt：模拟优化器（不真的训练，只是提供一个放 lr 的槽位）
# ==========================================
# 真实训练中我们用的是 torch.optim.AdamW，它有 param_groups 属性。
# 这里做一个"假优化器"：有 param_groups 结构，但不干任何实际的事，
# 因为我们只关心调度器能不能正确读写其中的 lr 字段。
class DummyOpt:
    def __init__(self):
        # param_groups 是 PyTorch 优化器的标准结构：一个列表，每个元素是一个字典。
        # 真实优化器里字典会包含 'params'（参数张量）、'lr'、'weight_decay' 等；
        # 这里只保留 'lr' 字段，用 0.0 初始化——初始学习率由调度器来设定，不是优化器。
        self.param_groups = [{'lr': 0.0}]

# ==========================================
# 测试函数：验证 warmup → cosine 学习率曲线的形状和边界
# ==========================================
def test_warmup_cosine_lr_progression():
    # ══════════════════════════════════════════════════════════
    # 第一步：创建优化器和调度器
    # ══════════════════════════════════════════════════════════
    # DummyOpt 模拟一个空的优化器，只用来承接 scheduler 写入的 lr。
    opt = DummyOpt()

    # 参数含义：
    #   warmup_steps=10  : 前 10 步线性爬坡（学习率从 0 → base_lr）
    #   total_steps=110  : 总共 110 步，减去 warmup 后，余弦衰减段有 100 步
    #   base_lr=1e-3     : 预热结束时达到的学习率峰值（也是 cosine 衰减的起点）
    #
    # 选择 warmup=10, total=110 的原因：
    #   warmup 占比 ~9%（略低于常见的 10%），足够验证"上升"行为；
    #   total=110 让余弦衰减段有 100 步，方便肉眼看出下降趋势。
    sch = WarmupCosineLR(opt, warmup_steps=10, total_steps=110, base_lr=1e-3)

    # ══════════════════════════════════════════════════════════
    # 第二步：运行整个调度周期，收集每一步的学习率
    # ══════════════════════════════════════════════════════════
    # 语法：[sch.step() for _ in range(110)] 是列表推导式（List Comprehension）。
    # `_` 是 Python 惯例，表示"循环变量我不需要，只是为了跑 110 次"。
    # 每次调用 sch.step() 会：
    #   1. step_num += 1（推进内部计数器）
    #   2. 根据公式算出当前步的 lr
    #   3. 写入 opt.param_groups（模拟真实训练中"修改优化器学习率"）
    #   4. 返回 lr（方便我们收集和检查）
    lrs = [sch.step() for _ in range(110)]

    # ══════════════════════════════════════════════════════════
    # 第三步：验证学习率曲线的三条核心约束
    # ══════════════════════════════════════════════════════════

    # ─── 约束 1：上界检查 ───
    # 学习率在任何时间点都不能超过 base_lr + 极小容差。
    # 这里的 +1e-12 是为了容忍浮点数舍入误差（cos(0) 理论上 = 1.0，
    # 但 base_lr * 0.5 * (1 + 1.0) 可能因浮点精度得到 1e-3 + 1e-16 这样的微扰）。
    # 语法：max(lrs) 取列表中所有学习率的最大值。
    assert max(lrs) <= 1e-3 + 1e-12

    # ─── 约束 2：warmup 阶段单调上升 ───
    # 在 warmup 阶段，学习率应该严格递增：
    #   第 0 步（索引 lrs[0]）≈ 1e-4 (base_lr * 1/10)
    #   第 9 步（索引 lrs[9]）≈ 1e-3 (base_lr * 10/10 = 峰值)
    # 所以 lrs[0] < lrs[9] 必须成立。
    # 如果这一步失败了，说明 warmup 公式 step_num/warmup_steps 有 bug、
    # 或者调度器内部的 step_num 计数乱掉了。
    assert lrs[0] < lrs[9]  # warmup increasing

    # ─── 约束 3：cosine 衰减阶段单调下降 ───
    # 结束 warmup 后（lrs[10]），学习率开始沿余弦曲线下降：
    #   lrs[10]  ≈ base_lr（刚刚结束 warmup，还在峰值）
    #   lrs[-1]  ≈ 0（最后一步，cos 降到最低）
    # 所以 lrs[-1] < lrs[10] 必须成立。
    # 语法：lrs[-1] 是 Python 的负数索引，等价于 lrs[len(lrs)-1]，即取列表最后一个元素。
    # 如果这一步失败了，说明余弦公式（0.5 * base_lr * (1+cos(...))）退化成常量
    # 或者 progress 计算的分母 total_steps - warmup_steps 出了问题（如为 0）。
    assert lrs[-1] < lrs[10]  # cosine decays
