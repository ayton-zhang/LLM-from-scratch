# ==========================================
# 测试：BPETokenizer 的分词器完整生命周期
# ==========================================
# BPE（Byte Pair Encoding）是 LLM 领域的"标准分词方案"，
# GPT-2/3/4、LLaMA、Mistral 等主流模型都在用它。
# 这个测试验证 BPETokenizer 的四个核心能力：
#   1. 训练（train）   ：从原始文本中学出子词合并规则
#   2. 保存（save）    ：把训练好的分词器序列化到磁盘
#   3. 加载（load）    ：从磁盘恢复分词器（跨进程/跨机器可用）
#   4. 编码（encode）  ：把人类可读的文本转成模型能吃的整数 token 序列
#
# 整个测试是一个"圆圈"（roundtrip）：训练→保存→加载→编码，
# 确保每个环节的数据流都能正确传递。

import os, tempfile
from tokenizer_bpe import BPETokenizer

# ==========================================
# 测试函数：BPE 分词器的训练-保存-加载-编码全流程
# ==========================================
# 函数名刻意描述了完整的数据流方向："train → save → load → roundtrip"，
# 即从原始文本出发，经过训练、持久化、恢复，最终验证编码结果正确。
def test_bpe_train_save_load_roundtrip():
    # ══════════════════════════════════════════════════════════
    # 第一步：在临时目录中创建极小的训练语料
    # ══════════════════════════════════════════════════════════
    # 语法：tempfile.TemporaryDirectory() 是 Python 标准库的上下文管理器，
    # with 块内创建一个临时文件夹，退出时自动删除（无论是否抛异常）。
    # 这样做的好处：测试不会留下任何磁盘垃圾，且每次运行都是干净的环境。
    with tempfile.TemporaryDirectory() as d:
        # 在临时目录下创建一个名为 tiny.txt 的文本文件，
        # 只包含 "hello hello world" 这 3 个"词"（12 个字符）。
        # 语料极小是刻意为之——这是单元测试，不是真实训练，
        # 我们只需要验证数据管道能跑通，不需要学出有意义的子词。
        txt = os.path.join(d, 'tiny.txt')
        with open(txt, 'w') as f:
            f.write('hello hello world')

        # ══════════════════════════════════════════════════════════
        # 第二步：训练 BPE 分词器
        # ══════════════════════════════════════════════════════════
        # 创建一个新的 BPETokenizer 实例。
        # vocab_size=100 意味着词表最终会有 100 个 token，包含：
        #   - 256 个基础单字节 token（BPE 的起点）
        #   - 外加直到 vocab_size 的合并 token（从语料中学出的子词组合）
        # 注意：100 对于真实语料太小（GPT-2 用 50257），
        # 这里只是为了让测试跑得快——"hello" 的字节序列足够短，100 个 token 够用。
        tok = BPETokenizer(vocab_size=100)

        # 在 tiny.txt 上执行 BPE 训练。
        # 底层调用 HuggingFace tokenizers 库的 ByteLevelBPETokenizer.train()，
        # 它会反复统计相邻 token 对的频率，把最高频的对合并成新 token，
        # 直到词表满 vocab_size=100 或没有更多可合并的对。
        tok.train(txt)

        # ══════════════════════════════════════════════════════════
        # 第三步：保存分词器到磁盘
        # ══════════════════════════════════════════════════════════
        # 训练完的分词器包含两张核心"表"：
        #   1. 词表（vocab）        ：token ID → 字节序列的映射
        #   2. 合并规则（merges）   ：哪两个 token 应该合并为一个
        # 保存就是把这两张表序列化成文件（底层是 JSON + 二进制），
        # 以便后续训练或推理时能加载完全相同的分词器。
        out = os.path.join(d, 'tok')
        tok.save(out)  # 会在 d/ 下生成 tok.json 和 tok/merges.txt（或类似结构）

        # ══════════════════════════════════════════════════════════
        # 第四步：从磁盘加载分词器（模拟"重启后恢复"场景）
        # ══════════════════════════════════════════════════════════
        # 创建一个全新的、未经训练的 BPETokenizer 实例（vocab_size 用默认值），
        # 然后从刚才保存的文件中恢复——验证 save/load 的序列化正确性。
        # 这是 checkpoint/resume 训练流程的基础：
        # 如果分词器不能精确恢复，整个训练的语义就丢了。
        tok2 = BPETokenizer()
        tok2.load(out)  # 从 tok.json 恢复词表和合并规则

        # ══════════════════════════════════════════════════════════
        # 第五步：用加载的分词器编码文本，验证结果正确
        # ══════════════════════════════════════════════════════════
        # encode("hello world") 把字符串转成整数 token ID 列表，
        # 底层流程：字符串 → 字节序列 → 按 BPE 合并规则分组 → token ID 列表。
        # 例如 "hello" 可能被编码为 [72, 101, 108, 108, 111]（5 个字节级 token）
        # 或 [某一个合并后的子词 token ID]，取决于 BPE 学到了什么合并规则。
        ids = tok2.encode('hello world')

        # 语法：isinstance(obj, type) 检查 obj 是否是指定类型的实例。
        # 这里要求 encode 返回的是 list 类型（不是 tensor、不是 generator）。
        # len(ids) > 0 确保编码结果不是空列表——分词器确实产生了 token。
        # 注意：这里不检查具体的 token ID 值（太脆弱），只检查"是否产出了东西"。
        # 实际训练中 token ID 的具体值取决于语料和随机的合并顺序，
        # 单元测试应该只断言"结构正确"，不绑定具体数值。
        assert isinstance(ids, list) and len(ids) > 0
