# ==========================================
# Part 5 单元测试二：MoE 层前向传播的形状保真 + 梯度流通验证
# ==========================================
#
# 本测试文件验证 moe.py 中 MoE 调度器的两个关键契约：
#   1. 输出形状必须与输入完全一致——残差连接的硬性要求
#   2. 梯度必须能从输出反向传播到所有子模块——门控和专家都需要训练
#
# 与前一个测试（test_gate_shapes.py）的关系：
#   test_gate_shapes 只测门控模块的独立行为（形状、权重范围），
#   本测试则把门控和专家拼在一起，验证 MoE 整体（gate + dispatch + combine）
#   的端到端行为。这是"集成测试"——测的不是某个组件本身，而是组件之间的协作。
#
# 为什么单独测试梯度流通如此重要？
#   MoE 的 dispatch/combine 阶段涉及大量的索引、散射和条件分支（if sel.any()），
#   这些操作在某些情况下可能打断 PyTorch 的自动微分图（computation graph）。
#   如果梯度在 dispatch 阶段丢失，门控的参数就永远无法被更新——模型会用随机路由
#   训练到天荒地老也不会收敛。梯度流测试是 MoE 最容易踩的坑，必须覆盖。

import torch
from moe import MoE


# ==========================================
# test_moe_forward_dims_and_grad：验证 MoE 前向形状 + 反向梯度
# ==========================================
def test_moe_forward_dims_and_grad():
    # ==========================================
    # 测试一：构建小型 MoE + 带梯度追踪的随机输入
    # ==========================================
    # B = batch_size（批次大小），2 个样本确保跨样本路由也被验证
    # T = sequence_length（序列长度），8 个 token 让路由有足够的多样性
    # C = dim（隐藏维度），32 维——小但足以验证维度逻辑

    # 语法：B,T,C = 2,8,32 是多变量赋值，三个值依次赋给三个变量。
    #   注意这里用的是取模赋值（不是元组解包），等号两边元素个数必须严格相等。
    B, T, C = 2, 8, 32

    # ─── 构建待测模块：MoE ───
    # 参数说明：
    #   dim=C=32   → 输入/输出隐藏维度
    #   n_expert=4 → 4 个专家（多于 k=1，确保路由有区分度）
    #   k=1        → 每个 token 只激活 1 个专家（Switch Transformer 风格，最稀疏）
    #                使用 k=1 而非 k=2 来测试最简单路由路径下的梯度流——
    #                如果 k=1 不能传播梯度，k=2 也必然不能。
    moe = MoE(dim=C, n_expert=4, k=1)

    # torch.randn(B, T, C, requires_grad=True) 生成 (2, 8, 32) 的随机张量。
    #
    # 语法：requires_grad=True 是关键参数，告诉 PyTorch：
    #   "请为这个张量构建计算图，记录所有对它做的操作"。
    # 只有设置了 requires_grad=True 的张量，PyTorch 才能在其上调用 .backward()
    # 并计算梯度。如果遗漏这个参数，后续 loss.backward() 不会报错但也不会
    # 产生任何梯度——这是一个常见的"静默 bug"，测试中必须显式设置。
    #
    # 类比：requires_grad 就像在快递包裹上贴了"追踪单号"——
    #   有了追踪单号（True），才能查到包裹经过了哪些站点（梯度怎么传的）；
    #   没有追踪单号（False），包裹照样送到，但你不知道它怎么来的。
    x = torch.randn(B, T, C, requires_grad=True)

    # ═══════════════════════════════════════════════════════
    # 测试二：前向传播——验证输出形状保真
    # ═══════════════════════════════════════════════════════
    # moe(x) 调用 MoE.forward(x)，内部流程：
    #   1. 展平：(B,T,C) = (2,8,32) → (S,C) = (16,32)，S = B*T = 16
    #   2. 门控路由：TopKGate(x_flat) → idx(16,1), w(16,1), aux(标量)
    #   3. dispatch + 专家计算：16 个 token 被分配到 4 个专家，每个专家处理子集
    #   4. combine：用门控权重加权融合专家输出
    #   5. 恢复形状：(16,32) → (2,8,32)
    #
    # 语法：`y, aux = moe(x)` 是元组解包。
    #   MoE.forward() 返回 (输出, aux_loss) 二元组。
    y, aux = moe(x)

    # ─── 断言 1：输出形状必须与输入形状完全相同 ───
    # 这是 Transformer 残差连接的基本要求：x = x + moe(norm(x))。
    # 如果 MoE 的输出形状不对（比如展平后忘了恢复），残差加法会因维度不匹配而报错。
    # 形状：(2, 8, 32) == (2, 8, 32) ✓
    assert y.shape == x.shape

    # ═══════════════════════════════════════════════════════
    # 测试三：反向传播——验证梯度能流通到所有子模块
    # ═══════════════════════════════════════════════════════
    # 本测试的核心逻辑：
    #   构造一个包含主输出 + 辅助损失的总损失 → 反向传播 → 检查参数是否有梯度。
    #
    # 为什么损失需要"主输出 + 辅助损失"两部分？
    #   主输出 (y**2).mean()：确保 MoE 的前向输出能反传梯度到所有子模块。
    #   辅助损失 0.01*aux：确保门控的负载均衡分支（在 gate.forward 中计算）
    #                    也能产生有效的梯度，让门控参数 w_g 得到更新。
    #   如果只用主输出，aux_loss 是"死分支"——它在计算图中存在但对 loss 没贡献，
    #   PyTorch 会跳过它的反向传播（除非用 retain_graph 等手段强制保留）。

    # 构造总损失：
    #   (y**2).mean()：y 的均方值，是一个标量。选择平方取平均作为"伪损失"，
    #     因为它总是非负且计算简单——任何能对 y 求导的标量都可以，不关心语义。
    #   0.01 * aux：0.01 是辅助损失的缩放系数（chosen to be small）。
    #     在实践中，MoE 论文推荐的 λ（辅助损失权重）通常在 0.001~0.1 之间。
    #     设 0.01 避免辅助损失主导总损失——主任务（y 的语义）仍应占主导。
    loss = (y ** 2).mean() + 0.01 * aux

    # ─── 反向传播 ───
    # 语法：loss.backward()
    #   从 loss 标量出发，沿着计算图逆向遍历，用链式法则计算每个参与运算的
    #   参数的梯度（∂loss/∂param），并将结果累加到 param.grad 中。
    #   PyTorch 的自动微分引擎（autograd）自动处理所有复杂的链式求导——
    #   你只需要写前向传播代码，反向传播完全自动。
    loss.backward()

    # ─── 断言 2：至少有一个参数获得了梯度 ───
    # 语法：moe.parameters()
    #   moe.parameters() 返回一个生成器（generator），遍历 MoE 及其所有子模块
    #   （gate、experts）中所有可训练的参数（nn.Parameter）。
    #   这包括：gate.w_g.weight/bias + 每个 ExpertMLP 的 Linear 权重。
    #   如果使用 nn.ModuleList 储存专家，.parameters() 会自动递归收集所有专家的参数；
    #   如果误用了普通 list，参数会被遗漏——梯度测试能发现这个 bug。
    #
    # 语法：列表推导式 [p.grad is not None for p in moe.parameters()]
    #   遍历每个参数 p，检查其 .grad 属性是否为 None。
    #   p.grad is not None → True 表示该参数获得了梯度（参与了计算图）
    #   p.grad is None     → False 表示该参数没有梯度（可能是"死参数"）
    #   返回一个布尔列表，如 [True, True, False, True, ...]
    #
    # 为什么用 any() 而非 all()？
    #   在实际的 MoE 前向传播中，由于 k=1 且路由是稀疏的，可能某些专家的参数
    #   在本次前向中没有被任何 token 选中（sel.any() 返回 False），
    #   导致该专家的计算被完全跳过——这种情况下该专家的参数不会出现在计算图中，
    #   .grad 自然为 None。这是 MoE 的固有特性，不是 bug。
    #   因此我们只要求"至少有一个参数有梯度"，而非"所有参数都有梯度"。
    #   更严格的检查可以通过多次前向传播（每次路由分布不同）取交集来实现。
    grads = [p.grad is not None for p in moe.parameters()]

    # 语法：any(grads)
    #   内置函数 any()：只要可迭代对象中有一个 True，就返回 True。
    #   这里验证"至少有一个参数收到了梯度信号"。
    #   如果没有任何参数有梯度，说明计算图在 dispatch 或 combine 阶段断裂了——
    #   这是一个严重 bug，必须被这个断言拦截。
    #
    # 类比：梯度就像"水流"——
    #   管道入口开了（loss.backward()），我们需要确认水至少流到了一些龙头
    #   （any param 有 grad）。如果所有龙头都是干的（grad 全 None），说明
    #   管道中间断了。至于是某个龙头没水（某个专家没被选中），那是正常的——
    #   MoE 的设计就是每次只开部分龙头。
    assert any(grads)

    # 补充说明（非测试断言，仅作注释）：
    # 对于 k=1 的 MoE，在一次 forward 中，最多只有被选中的 k 个专家（及门控）
    # 的参数会获得梯度。如果需要验证"所有专家最终都能被训练到"，可以写一个
    # 更复杂的测试：用不同的随机种子跑 N 次 forward+backward，统计各专家被
    # 更新的次数。这种"覆盖性测试"在大型 MoE 模型中非常重要——
    # 某专家如果长时间不被选中，它的参数会"冻结"在初始化状态，浪费容量。
