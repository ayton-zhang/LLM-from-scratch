# ==========================================
# Part 5 单元测试一：门控（TopKGate）的形状与语义验证
# ==========================================
#
# 本测试文件验证 gating.py 中 TopKGate 模块的核心契约：
#   1. 输出形状是否正确——门控返回的 (indices, weights, aux_loss) 维度是否符合预期
#   2. 权重的取值范围是否正确——softmax 概率的非负性 + 上界约束
#   3. 辅助损失是否是标量——aux_loss 应该是一个 0 维张量（单个数值）
#
# 为什么形状测试是深度学习项目的第一道防线？
#   PyTorch 的张量操作对形状极其敏感——如果门控输出形状对不上 MoE 层的 dispatch
#   逻辑（如 idx 的列数不等于 k），代码不会在 forward 时立即报错，而是在 scatter
#   或索引阶段产生难以调试的"静默错误"（比如广播把无关 token 累加到一起）。
#   形状测试能在问题最早阶段拦截这类 bug，避免在复杂模型中发现时难以定位。


import torch
from gating import TopKGate


# ==========================================
# test_gate_topk_shapes：验证门控输出的形状 + 权重的数学性质
# ==========================================
def test_gate_topk_shapes():
    # ==========================================
    # 测试一：构建小型输入 + 小型门控
    # ==========================================
    # 选择小的尺寸是为了测试跑得快（毫秒级），但又足够验证形状逻辑。
    # 测试不需要"真实"尺寸——32 个 token 和 32000 个 token 的形状规则相同。

    # S = 总 token 数（相当于 batch_size × seq_len 展平后的结果，即 (B*T)）
    # C = 隐藏维度（dim），与模型配置中的 n_embd 含义相同
    # E = 专家数（n_expert）
    # K = top-k（每个 token 选几个专家）
    S, C, E, K = 32, 64, 4, 2

    # torch.randn(S, C) 从标准正态分布 N(0,1) 随机采样，生成 (32, 64) 的浮点张量。
    x = torch.randn(S, C)

    # 实例化门控模块：dim=64, n_expert=4, k=2
    # 内部创建了一个 nn.Linear(64, 4, bias=True) 权重矩阵
    gate = TopKGate(C, E, k=K)

    # ═══════════════════════════════════════════════════════
    # 测试二：前向传播，获取门控输出
    # ═══════════════════════════════════════════════════════
    # gate(x) 调用 TopKGate.forward(x)，内部流程：
    #   1. Linear 投影：(S, C) → (S, E)，即 (32, 64) → (32, 4)
    #   2. Softmax 归一化：(S, E) → (S, E)，每行变为概率分布
    #   3. TopK 选择：从 (S, E) 中每行取前 K 个 → idx(S, K) + w(S, K)
    #   4. 辅助损失计算：标量 aux_loss
    #
    # 语法：`idx, w, aux = gate(x)` 是三元组解包（Triple Unpacking）。
    #   TopKGate.forward() 返回 (indices, weights, aux_loss) 三个值，
    #   Python 自动把它们分别绑定到 idx、w、aux 三个变量。
    idx, w, aux = gate(x)

    # ─── 断言 1：专家索引 idx 的形状必须是 (S, K) ───
    # idx[i, j] = 第 i 个 token 在第 j 个槽位上选中的专家编号（0 ~ E-1 的整数）。
    # S=32（32 个 token），K=2（每个 token 选 2 个专家）→ idx 形状应为 (32, 2)。
    # 如果 idx 形状不对，后续 MoE 层的 dispatch 逻辑（用 idx 索引专家列表）会出错。
    assert idx.shape == (S, K)

    # ─── 断言 2：门控权重 w 的形状必须是 (S, K) ───
    # w[i, j] = 第 i 个 token 的第 j 个专家的 softmax 概率值（即门控权重）。
    # w 和 idx 形状必须一致（都是 (S, K)）——每个 token 有 K 个专家，对应 K 个权重。
    # 如果形状不一致，MoE 层的 combine 阶段（y += w * y_e）会因为广播问题出错。
    assert w.shape == (S, K)

    # ─── 断言 3：辅助损失 aux 必须是标量（0 维张量）───
    # 语法：.ndim 返回张量的维度数（number of dimensions）。
    #   标量张量（如 torch.tensor(3.14)）→ ndim=0，形状是空的 torch.Size([])
    #   一维向量（如 torch.tensor([1., 2.])）→ ndim=1，形状是 torch.Size([2])
    # 辅助损失必须是标量，因为训练循环需要把它加到一个 total_loss 上——
    #   非标量的损失无法反向传播（PyTorch 的 .backward() 要求损失是 0 维标量）。
    assert aux.ndim == 0

    # ═══════════════════════════════════════════════════════
    # 测试三：验证门控权重的数学性质（概率约束）
    # ═══════════════════════════════════════════════════════
    # 门控权重来自 softmax 归一化，因此必须满足两个数学性质：
    #   性质 1（非负性）：每个权重 ≥ 0（exp(x)/Σexp(x) 的分子分母都 > 0）
    #   性质 2（上界）：每个权重 ≤ 1（概率值，但注意：K 个求和后 ≤ 1，单个 ≤ 1 必然成立）
    #
    # 为什么需要测试这两个看似"显然"的性质？
    #   Softmax 的理论保证依赖于数值稳定实现（PyTorch 的 softmax 内部有
    #   exp 的溢出保护）。如果实现有 bug（如用原始 exp 除以非稳定的求和），
    #   可能出现 NaN 或 inf，这些异常值往往以"权重在 [-inf, inf]"的形式出现。
    #   在大型模型中，这类 bug 可能在训练数千步后才触发，极难排查。
    #   测试在初始化阶段就覆盖这些边界条件，是成本最低的防御手段。

    # 语法：torch.all(w >= 0)
    #   w >= 0 是对张量逐元素比较，返回同形的布尔张量，如 [[True,True],[False,...],...]
    #   torch.all(...) 检查是否所有元素都为 True
    #   效果：验证门控权重中没有负数
    assert torch.all(w >= 0)

    # 语法：torch.all(w <= 1)
    #   同理，验证所有权重 ≤ 1
    #   注意：对于 k>1 的情况，单个 token 的 k 个权重之和可能略小于 1
    #   （因为 top-k 选出的只是概率最高的 k 个，不是所有 E 个专家的完整分布）。
    #   但每个单独的权重一定是 ≤ 1 的——如果所有权重之和才 ≤ 1，单个必定 ≤ 1。
    assert torch.all(w <= 1)

    # 补充说明（非测试断言，仅作注释）：
    # 如果要进一步验证，常见的增强断言包括：
    #   1. idx 的值在 [0, E) 范围内：assert torch.all(idx >= 0) and torch.all(idx < E)
    #   2. idx 的每一行 K 个专家编号互不相同（top-k 保证无重复采样）
    #   3. w 沿 K 维求和 ≤ 1：top-k softmax 权重是"截断"概率，和 ≤ 完整分布的 1
    # 这里保持精简——只测最关键的形状和数值范围。
