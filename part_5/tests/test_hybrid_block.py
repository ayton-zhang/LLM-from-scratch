# ==========================================
# Part 5 单元测试三：混合 Block（HybridFFN）的形状与辅助损失验证
# ==========================================
#
# 本测试文件验证 block_hybrid.py 中 HybridFFN 模块的核心契约：
#   1. 输出形状是否与输入一致——残差连接要求 y.shape == x.shape
#   2. 辅助损失 aux_loss 是否非负——负载均衡损失本质是标量乘积和，预期 ≥ 0
#
# HybridFFN 是 Part 5 最上层的集成模块（稠密 FFN + MoE 并联），
# 如果前两层的测试（test_gate_shapes、test_moe_forward）已经通过，
# 本测试重点验证"组合后"的行为——两部分拼接在一起后形状和梯度流是否依然正确。
#
# 与前两个测试的关系（测试金字塔）：
#   test_gate_shapes.py   → 底层：验证门控的独立行为
#   test_moe_forward.py   → 中层：验证 MoE（门控+专家）的组合行为
#   test_hybrid_block.py  → 顶层：验证 HybridFFN（稠密+MoE）的集成行为
#   每一层依赖下一层的正确性，问题定位时从顶层往底层排查。

import torch
from block_hybrid import HybridFFN


# ==========================================
# test_hybrid_ffn_blend：验证混合 FFN 的形状保真 + 辅助损失非负
# ==========================================
def test_hybrid_ffn_blend():
    # ==========================================
    # 测试一：构建小型 HybridFFN + 模拟输入
    # ==========================================
    # B = batch_size（批次大小），设为 1 是最简单的测试情况
    # T = sequence length（序列长度），4 个 token 足够验证 shape 逻辑
    # C = dim（隐藏维度），16 足以让专家路由有区分度

    # 语法：B, T, C = 1, 4, 16 是一次性给三个变量赋值的多变量赋值（不是元组解包，
    #   是 Python 的多重赋值语法）。等号右边三个值依次赋给左边三个变量。
    B, T, C = 1, 4, 16

    # ─── 构建待测模块：HybridFFN ───
    # 参数选择含义：
    #   alpha=0.3  → 30% 稠密 FFN + 70% MoE，偏向 MoE 侧。
    #                这样 aux_loss 更容易产生非零值（MoE 占比大）。
    #                如果设 alpha=1.0（纯稠密），MoE 虽仍执行但输出会被 (1-0)=0 压成零。
    #   n_expert=3 → 3 个专家。设得比 k 大（3 > 2），确保路由有选择空间。
    #   k=2        → 每个 token 激活 2 个专家（Mixtral 风格，k 略大于 1 增加容错）。
    ffn = HybridFFN(dim=C, alpha=0.3, n_expert=3, k=2)

    # torch.randn(B, T, C) 生成 (1, 4, 16) 的随机张量，模拟一个 batch 的隐状态。
    # 不需要 requires_grad（本测试不验证梯度），只验证前向传播的输出属性。
    x = torch.randn(B, T, C)

    # ═══════════════════════════════════════════════════════
    # 测试二：前向传播，获取混合输出
    # ═══════════════════════════════════════════════════════
    # ffn(x) 调用 HybridFFN.forward(x)，内部流程：
    #   1. dense(x) → y_dense    形状 (B, T, C)，稠密 FFN 通路
    #   2. moe(x)   → y_moe, aux 形状 (B, T, C) + 标量，MoE 通路
    #   3. y = α·y_dense + (1-α)·y_moe  凸组合混合
    #
    # 语法：`y, aux = ffn(x)` 是二元组解包。
    #   HybridFFN.forward() 返回 (输出, aux_loss) 两个值，
    #   Python 自动把它们绑定到 y 和 aux。
    y, aux = ffn(x)

    # ─── 断言 1：输出形状必须与输入形状完全相同 ───
    # 这是 Transformer 残差连接的基本要求——FFN 子层（无论内部是稠密还是 MoE）
    # 的输出必须能与输入做逐元素加法：x = x + ffn(norm(x))。
    # 如果形状不一致，加法会触发广播（错误行为）或直接报错。
    # 例如：x 形状 (1,4,16)，y 形状 (1,4,32) → 无法残差相加。
    assert y.shape == x.shape

    # ─── 断言 2：辅助损失必须非负 ───
    # aux_loss = E × Σ_j (importance[j] × load[j])
    #   其中 importance[j] 是专家 j 的平均 softmax 概率（∈ [0, 1]）
    #         load[j] 是专家 j 被选中为首选的 token 占比（∈ [0, 1]）
    #   所以 aux_loss ≥ 0 在数学上恒成立。
    #
    # 为什么测试"非负"而非"等于某个精确值"？
    #   每次前向传播的随机输入不同，aux_loss 的具体值会在一个范围内波动。
    #   测试浮点数的精确值毫无意义——微小差异会导致脆弱的、频繁误报的测试。
    #   非负性是一个"恒真命题"（invariant），无论输入和随机种子如何变化都成立，
    #   是比精确值更可靠的测试断言。
    #
    # 语法：aux.item() 把 0 维标量张量转换为 Python float。
    #   .item() 只能用于包含单个值的张量（0 维或 1 元素的张量），
    #   如果 aux 不是标量，.item() 会直接报错——这间接验证了 aux 是标量。
    #   assert aux.item() >= 0.0：转换为普通 float 后与 0 比较。
    assert aux.item() >= 0.0

    # 补充说明（非测试断言）：
    # 如果要做更深入的测试，可以增加：
    #   1. 梯度流测试：y.sum().backward() 后检查 ffn 各参数是否有梯度
    #   2. α 边界测试：α=0 和 α=1 分别验证纯 MoE 和纯稠密的行为
    #   3. 负载均衡测试：多次前向传播，统计 aux 的均值和方差是否合理
    # 但当前测试保持最小化——只覆盖"组合后不崩、数值不异常"的基本面。
